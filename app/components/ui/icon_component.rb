    attr_reader :name, :size, :css_class

    def initialize(name:, size: :md, css_class: nil)
      @name = name.to_sym
      @size = size.to_sym
      @css_class = css_class

      raise ArgumentError, "Unknown icon: #{name}" unless ICONS.key?(@name)
      raise ArgumentError, "Unknown size: #{size}" unless SIZES.key?(@size)
    end

    def icon_path
      ICONS[name]
    end

    def size_class
      SIZES[size]
    end

    def classes
      [size_class, css_class].compact.join(" ")
    end

